#!/bin/bash
set -euo pipefail

echo "Creating/updating MonkyForce local development schema..."

sqlplus -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = FREEPDB1;

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*)
    INTO v_count
    FROM dba_users
   WHERE username = UPPER('${APP_DB_USERNAME}');

  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE USER ${APP_DB_USERNAME} IDENTIFIED BY "${APP_DB_PASSWORD}"';
  END IF;
END;
/

ALTER USER ${APP_DB_USERNAME} IDENTIFIED BY "${APP_DB_PASSWORD}";
ALTER USER ${APP_DB_USERNAME} QUOTA UNLIMITED ON USERS;

GRANT CREATE SESSION TO ${APP_DB_USERNAME};
GRANT CREATE TABLE TO ${APP_DB_USERNAME};
GRANT CREATE VIEW TO ${APP_DB_USERNAME};
GRANT CREATE SEQUENCE TO ${APP_DB_USERNAME};
GRANT CREATE PROCEDURE TO ${APP_DB_USERNAME};
GRANT CREATE TRIGGER TO ${APP_DB_USERNAME};

EXIT;
SQL

echo "MonkyForce schema ready."
